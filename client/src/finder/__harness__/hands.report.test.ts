// "npm run finder:hands": 12 Branded Dracotail hands of 5 going first (one built around each Main
// Deck starter, its other 4 cards seeded), each solved for 6 seconds at the real settings (width
// 60, growth 4), written to docs/finder/branded-dracotail-hands.md for the user to judge and try in
// Master Duel (spec check 4: this deck has no reference engine).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { splitItems } from '../engine/items';
import { BD_STARTERS, loadDracotail, starterHand } from './dracotail';

const OUT = fileURLToPath(new URL('../../../../docs/finder/branded-dracotail-hands.md', import.meta.url));
const SOLVE = { timeMs: 6000, width: 60, growth: 4, top: 3 };

describe('Branded Dracotail hands report', () => {
  it('writes the report', () => {
    const { engine } = loadDracotail();
    const props = engine.deck.props, ix = engine.deck.ix;
    const short = (id: string) => props[ix[id]]?.short ?? id;
    const out: string[] = [
      '# Branded Dracotail: hands to judge',
      '',
      'Generated by `client/src/finder/__harness__/hands.report.test.ts` (`npm run finder:hands` in `client/`). Do not edit by hand.',
      '',
      'Twelve going-first hands of 5, one built around each starter of the list (the other four cards seeded), each solved for 6 seconds at the real search settings. For each: the hand, the steps the Finder found, the end board, what it does on their turn and in the End Phase with the values it gave them, and the score. Please play them in Master Duel and say where a line is wrong or a value is off; how each card is modelled, and the rules I was unsure of, are in `.superpowers/sdd/2026-11-16-line-finder/task-G-report.md`.',
      '',
    ];
    BD_STARTERS.forEach((starter, i) => {
      const h = starterHand(starter, 9000 + i);
      const r = engine.solveBeam(engine.newState(h.cfg), SOLVE);
      expect(r.errors).toBe(0);
      const line = r.lines[0];
      const l = engine.serializeLine(line, h.hand, 'best');
      out.push(`## ${i + 1}. ${short(starter)}: ${h.hand.map(short).join(', ')}`, '');
      if (!l.steps.length) out.push('No line: nothing worth doing with this hand.', '');
      l.steps.forEach((s, k) => out.push(`${k + 1}. ${s.text}`));
      if (l.steps.length) out.push('');
      if (l.sets.length) out.push(`Then Set ${l.sets.map(short).join(', ')}.`, '');
      const board = l.board.mons.map((m) => short(m.id)).concat(l.board.st.map((x) => short(x.id) + (x.up ? '' : ' (Set)')));
      out.push(`End board: ${board.length ? board.join(', ') : 'nothing'}.`, '');
      const { turn, end } = splitItems(l.items);
      const list = (xs: [string, number][]) => xs.map(([t, v]) => `- ${t} (${v.toFixed(2)})`);
      out.push('On their turn:', ...(turn.length ? list(turn) : ['- nothing']), '');
      if (end.length) out.push('In the End Phase:', ...list(end), '');
      out.push(`Score ${line.score.toFixed(2)} (${r.nodes} positions searched in ${(r.ms / 1000).toFixed(1)} s).`, '');
    });
    writeFileSync(OUT, out.join('\n'));
  });
});
