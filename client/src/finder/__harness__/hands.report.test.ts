// "npm run finder:hands": 12 Branded Dracotail hands of 5 going first (one built around each Main
// Deck starter, its other 4 cards seeded), each solved for 6 seconds at the real settings (width
// 60, growth 4), written to docs/finder/branded-dracotail-hands.md for the user to judge and try in
// Master Duel (spec check 4: this deck has no reference engine).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { splitItems } from '../engine/items';
import { BD_STARTERS, loadDracotail, starterHand } from './dracotail';

const OUT = fileURLToPath(new URL('../../../../docs/finder/branded-dracotail-hands.md', import.meta.url));
const SOLVE = { timeMs: 6000, width: 60, growth: 4, top: 3 };

/** The Branded Dracotail rules the deck file models one way, simplifies or leaves out, in plain words. */
const UNMODELLED = [
  'Dracotail Mululu Fusion Summons only while it is on the field. Its text names no place; if it also works from the hand, some lines are missing.',
  'Fallen of the White Dragon counts as Fallen of Albaz everywhere (hand and Deck too); Albion the Shrouded Dragon only on the field and in the GY. Incredible Ecclesia can Special Summon Fallen of the White Dragon as "Fallen of Albaz".',
  'Dracotail Arthalion revived from the GY should be banished when it leaves the field. The Finder puts it in the GY instead; it no longer counts as a Fusion Monster sent to the GY, but it could still be used as material from the GY.',
  "Fallen of the White Dragon's Ecclesia, The Fallen & The Virtuous's revive and Secreterion's revive take Main Deck monsters only from your GY (the Finder does not track whether an Extra Deck monster in the GY was properly summoned), and never from their GY.",
  'Branded in High Spirits always discards the revealed monster and adds a card; with nothing to add (or under Droll & Lock Bird) it is not used at all.',
  "Branded Fusion's restriction starts when it resolves: the Finder does not stop it after a non-Fusion Extra Deck summon earlier in the turn.",
  'Dracotail Mululu always negates a face-up monster of theirs when it can (no downside to skipping).',
  'Not played at all: Triple Tactics Talent (the Finder does not record that they activated a monster effect), Predaplant Verte Anaconda copying Super Polymerization (it copies Branded Fusion only), changing Attributes (Mixousia, Hyperinvoked Aeon, Verte), The Dragon that Devours the Dogma shuffling cards back, Hyperinvoked Aeon banishing from their Extra Deck, Khaos Starsource and Granguignol effects when banished or on their turn, Mirrorjade destroying their monsters in the End Phase.',
  'Their-turn effects are fixed values, not played out: Incredible Ecclesia and Ecclesia and the Dark Dragon summoning Albaz to fuse with their monster (0.5 / 0.6), Blazing Cartesia, Dracotail Mululu and a Dracotail Faimena in hand Fusion Summoning (0.3-0.4), Mirrorjade (0.9), Rindbrumm (0.6), Mixousia (0.5), Secreterion (0.4).',
  'End Phase effects are fixed values: Titaniklad and Albion the Branded Dragon searches (0.5), Alba-Lenatus (0.4), Incredible Ecclesia, Blazing Cartesia and Branded in High Spirits returning to the hand (0.3 each, one copy), Ecclesia and the Dark Dragon coming back (0.5, only after its own effect).',
  'Mulcharmy Purulia is worth little in hand (0.2): after a combo you control cards, so it cannot be used on their turn.',
];

describe('Branded Dracotail hands report', () => {
  it('writes the report', () => {
    const { engine } = loadDracotail();
    const props = engine.deck.props, ix = engine.deck.ix;
    const short = (id: string) => props[ix[id]]?.short ?? id;
    const out: string[] = [
      '# Branded Dracotail: hands to judge',
      '',
      'Generated by `client/src/finder/__harness__/hands.report.test.ts` (`npm run finder:hands` in `client/`). Do not edit by hand.',
      '',
      'Twelve going-first hands of 5, one built around each starter of the list (the other four cards seeded), each solved for 6 seconds at the real search settings. For each: the hand, the steps the Finder found, the end board, what it does on their turn and in the End Phase with the values it gave them, and the score. Please play them in Master Duel and say where a line is wrong or a value is off.',
      '',
      '## What the Finder does not know yet', '',
      'These rules are modelled one way, simplified or left out. A line that depends on one of them may be wrong or missing:', '',
      ...UNMODELLED.map((x) => '- ' + x), '',
    ];
    BD_STARTERS.forEach((starter, i) => {
      const h = starterHand(starter, 9000 + i);
      const r = engine.solveBeam(engine.newState(h.cfg), SOLVE);
      expect(r.errors).toBe(0);
      const line = r.lines[0];
      const l = engine.serializeLine(line, h.hand, 'best');
      out.push(`## ${i + 1}. ${short(starter)}: ${h.hand.map(short).join(', ')}`, '');
      if (!l.steps.length) out.push('No line: nothing worth doing with this hand.', '');
      l.steps.forEach((s, k) => out.push(`${k + 1}. ${s.text}`));
      if (l.steps.length) out.push('');
      if (l.sets.length) out.push(`Then Set ${l.sets.map(short).join(', ')}.`, '');
      const board = l.board.mons.map((m) => short(m.id)).concat(l.board.st.map((x) => short(x.id) + (x.up ? '' : ' (Set)')));
      out.push(`End board: ${board.length ? board.join(', ') : 'nothing'}.`, '');
      const { turn, end } = splitItems(l.items);
      const list = (xs: [string, number][]) => xs.map(([t, v]) => `- ${t} (${v.toFixed(2)})`);
      out.push('On their turn:', ...(turn.length ? list(turn) : ['- nothing']), '');
      if (end.length) out.push('In the End Phase:', ...list(end), '');
      out.push(`Score ${line.score.toFixed(2)} (${r.nodes} positions searched in ${(r.ms / 1000).toFixed(1)} s).`, '');
    });
    writeFileSync(OUT, out.join('\n'));
  });
});
