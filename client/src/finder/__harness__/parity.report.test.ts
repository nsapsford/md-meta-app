// The DM Azamina parity report (docs/finder/dm-azamina-parity-report.md), one script, two parts:
//  - "scores" (npm run finder:report): every situation at PIN through both engines; the counts
//    (same, higher, lower), every ACCEPTED entry with its reason, and for each situation where the
//    new engine scores higher (or lower) both lines side by side with the new line's ledger result.
//  - "bench" (npm run finder:bench): the set at the real settings (width 60, growth 4, 2.5 s) through
//    both engines; every situation where the new engine scored lower in equal time. Timing varies:
//    read by a person, not a gate.
// Each part rewrites its own section of the file and keeps the other.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import type { Engine, LineEval } from '../engine';
import type { GeneratedLine as LedgerLine } from '../../../../server/src/services/lineGen/types';
import { ACCEPTED, ACCEPTED_EXPORT, ACCEPTED_EXPORT_TEXT, ACCEPTED_LEDGER } from './acceptedDiffs';
import { loadDeckFiles } from './groupParity';
import { checkGenerated, dmDeckContext, showIssue } from './ledger';
import { loadReference, type RefEngine } from './loadReference';
import { handOf, newRoot, readBaseline, SCORE_EPS } from './runSituation';
import { toIntr } from './mapping';
import { buildSituations, PIN, refRoot, type Situation } from './situations';

const OUT = fileURLToPath(new URL('../../../../docs/finder/dm-azamina-parity-report.md', import.meta.url));
const BENCH = { width: 60, growth: 4, timeMs: 2500, top: 3 } as const;
const BEGIN = (n: string) => `<!-- ${n}:begin -->`, END = (n: string) => `<!-- ${n}:end -->`;

/** Replace (or add) one section of the report. */
function writeSection(name: 'scores' | 'bench', body: string): void {
  let doc = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (!doc.startsWith('# DM Azamina')) doc = '# DM Azamina: new engine against the reference\n\nGenerated by `client/src/finder/__harness__/parity.report.test.ts` (`npm run finder:report`, `npm run finder:bench` in `client/`). Do not edit by hand.\n\n' + BEGIN('scores') + '\n' + END('scores') + '\n\n' + BEGIN('bench') + '\n' + END('bench') + '\n';
  const a = doc.indexOf(BEGIN(name)), b = doc.indexOf(END(name));
  doc = doc.slice(0, a + BEGIN(name).length) + '\n' + body.trimEnd() + '\n' + doc.slice(b);
  writeFileSync(OUT, doc);
}

const md = (t: string) => t.replace(/\|/g, '\\|');
const stepTexts = (s: any): string[] => s.log.map((x: any) => x.text + (x.interrupted ? ` [${x.interrupted}]` : ''));

interface Side { score: number; steps: string[]; board: string; generated: LedgerLine }

function sideBySide(sit: Situation, ref: Side, neu: Side, ledger: string): string {
  const out = [`### ${sit.id} (${sit.group})`, '', `Hand: ${handOf(sit).join(', ')}${sit.policy ? `; opponent: ${sit.policy.map((p) => p.label ?? p.kind).join(' + ')}` : ''}${sit.cfg.opp ? '; opponent field set' : ''}${sit.cfg.mul ? `; draw effects ${sit.cfg.mul}` : ''}${sit.cfg.base ? `; continues after ${sit.cfg.base.length} steps` : ''}`, ''];
  out.push(`| | Reference | New engine |`, `|---|---|---|`);
  out.push(`| Score | ${ref.score.toFixed(4)} | ${neu.score.toFixed(4)} |`);
  out.push(`| End board | ${md(ref.board)} | ${md(neu.board)} |`);
  const n = Math.max(ref.steps.length, neu.steps.length);
  for (let i = 0; i < n; i++) out.push(`| ${i + 1} | ${md(ref.steps[i] ?? '')} | ${md(neu.steps[i] ?? '')} |`);
  out.push('', `Ledger checker on the new line: ${ledger}`, '');
  return out.join('\n');
}

function ledgerText(g: LedgerLine, ctx: ReturnType<typeof dmDeckContext>): { ok: boolean; text: string } {
  const r = checkGenerated(g, ctx);
  const parts = [r.errors.length ? `**${r.errors.length} error(s)**: ${r.errors.map(showIssue).join('; ')}` : 'no errors'];
  if (r.accepted.length) parts.push(`${r.accepted.length} explained by ACCEPTED_LEDGER (${r.accepted.map(showIssue).join('; ')})`);
  if (r.warnings.length) parts.push(`${r.warnings.length} warning(s): ${r.warnings.map(showIssue).join('; ')}`);
  const text = parts.join('; ');
  return { ok: r.errors.length === 0, text: text.endsWith('.') ? text : text + '.' };
}

describe('parity report', () => {
  const { engine: ref, cards } = loadReference();
  const sits = buildSituations(ref, cards);
  const loaded = loadDeckFiles();
  if (!loaded.ok) throw new Error(loaded.errors);
  const neu: Engine = loaded.engine;
  const ctx = dmDeckContext(cards);

  const refSide = (sit: Situation, path: string[]): Side => {
    const s = ref.replay({ ...sit.cfg, base: undefined }, path);
    const l = (ref as any).asLine(s);
    const g = ref.toGenerated(l, 'Reference', handOf(sit));
    return { score: l.score, steps: stepTexts(s), board: g.endBoardText ?? g.endBoard.join(', '), generated: g };
  };
  const newSide = (sit: Situation, l: LineEval): Side => {
    const g = neu.toGenerated(l, 'New engine', handOf(sit));
    return { score: l.score, steps: stepTexts(l.state!), board: g.endBoardText ?? g.endBoard.join(', '), generated: g as LedgerLine };
  };

  it('scores', () => {
    const base = readBaseline();
    const groups = new Map<string, { same: number; higher: number; lower: number }>();
    const higher: string[] = [], lower: string[] = [];
    let rejected = 0;
    for (const sit of sits) {
      const row = base.get(sit.id)!;
      const line = neu.solveBeam(newRoot(ref, neu, sit), { ...PIN, strict: true, policy: sit.policy?.map(toIntr) }).lines[0];
      const g = groups.get(sit.group) ?? { same: 0, higher: 0, lower: 0 };
      groups.set(sit.group, g);
      const d = line.score - row.score;
      if (Math.abs(d) <= SCORE_EPS) { g.same++; continue; }
      const a = refSide(sit, row.path), b = newSide(sit, line);
      const lg = ledgerText(b.generated, ctx);
      if (d > 0) { g.higher++; higher.push(sideBySide(sit, a, b, lg.text)); if (!lg.ok) rejected++; } else { g.lower++; lower.push(sideBySide(sit, a, b, lg.text)); }
    }
    const tot = [...groups.values()].reduce((t, g) => ({ same: t.same + g.same, higher: t.higher + g.higher, lower: t.lower + g.lower }), { same: 0, higher: 0, lower: 0 });
    const body: string[] = [
      '## Scores at the pinned beam', '',
      `Every situation (${sits.length}) through both engines at one round of width ${PIN.width}, never clock-limited, so results repeat. The reference's score is its recorded best (\`baseline.json\`). Scores within ${SCORE_EPS} are the same (the engines sum board values in a different order).`, '',
      '| Group | Same | Higher | Lower |', '|---|---|---|---|',
      ...[...groups].map(([k, g]) => `| ${k} | ${g.same} | ${g.higher} | ${g.lower} |`),
      `| **all** | **${tot.same}** | **${tot.higher}** | **${tot.lower}** |`, '',
      '## Accepted differences', '',
      'Lockstep move differences (`ACCEPTED`):', '',
      ...ACCEPTED.map((a) => `- (${a.side}${a.pairedWith ? ', paired' : ''}) ${a.reason}`), '',
      `Line Trainer export differences (\`ACCEPTED_EXPORT\`): ${ACCEPTED_EXPORT.length ? '' : 'none.'}`,
      ...ACCEPTED_EXPORT.map((a) => `- ${a.reason}`),
      `- End-board text: ${ACCEPTED_EXPORT_TEXT.reason}`, '',
      'Ledger checker errors that are the checker\'s, not the line\'s (`ACCEPTED_LEDGER`):', '',
      ...ACCEPTED_LEDGER.map((a) => `- ${a.reason}`), '',
      '## Higher than today', '',
      higher.length ? `${higher.length} situation(s); each new line was run through the ledger checker (${rejected ? `**${rejected} rejected**` : 'none rejected'}).` : 'None.', '',
      ...higher,
      '## Lower than today', '',
      lower.length ? `**${lower.length} situation(s) where the new engine scores lower.**` : 'None.', '',
      ...lower,
    ];
    writeSection('scores', body.join('\n'));
    console.info(`parity report: same ${tot.same}, higher ${tot.higher}, lower ${tot.lower}, higher lines rejected by the ledger ${rejected}`);
    expect(tot.same + tot.higher + tot.lower).toBe(sits.length);
    // A higher line the ledger checker rejects is not accepted.
    expect(rejected).toBe(0);
  });

  it('bench', () => {
    const rows: string[] = [];
    let lowerN = 0, higherN = 0, refNodes = 0, newNodes = 0;
    for (const sit of sits) {
      const a = (ref as RefEngine).solveBeam(refRoot(ref, sit.cfg), { ...BENCH, policy: sit.policy });
      const b = neu.solveBeam(newRoot(ref, neu, sit), { ...BENCH, policy: sit.policy?.map(toIntr) });
      refNodes += a.nodes; newNodes += b.nodes;
      const d = b.lines[0].score - a.lines[0].score;
      if (d > SCORE_EPS) higherN++;
      if (d < -SCORE_EPS) { lowerN++; rows.push(`| ${sit.id} | ${a.lines[0].score.toFixed(4)} | ${b.lines[0].score.toFixed(4)} | ${d.toFixed(4)} | ${a.width} / ${a.nodes} | ${b.width} / ${b.nodes} |`); }
    }
    const body = [
      '## Bench at the real settings', '',
      `Both engines with the solve task's settings (width ${BENCH.width}, growth ${BENCH.growth}, ${BENCH.timeMs} ms), one after the other on the same machine, on ${new Date().toISOString().slice(0, 10)}. Timing varies from run to run; this list is for reading, not a gate.`, '',
      `Positions explored in total: reference ${refNodes}, new engine ${newNodes}. New engine higher on ${higherN} situation(s), lower on ${lowerN}.`, '',
      ...(rows.length ? ['| Situation | Reference | New | Difference | Reference last width / positions | New last width / positions |', '|---|---|---|---|---|---|', ...rows] : ['No situation scored lower.']),
    ];
    writeSection('bench', body.join('\n'));
    console.info(`bench: lower ${lowerN}, higher ${higherN}`);
    expect(rows.length).toBe(lowerN);
  }, 3_600_000);
});
