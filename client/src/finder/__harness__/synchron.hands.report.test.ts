// "npm run finder:hands": Synchron hands of 5 going first (one built around each Main Deck starter,
// its other 4 cards seeded, then a few common two-card openers), each solved for 6 seconds at the
// real settings (width 60, growth 4), written to docs/finder/synchron-hands.md for the user to judge
// and try in Master Duel (this deck has no reference engine).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { splitItems } from '../engine/items';
import { fixedHand, loadSynchron, starterHand, SY_STARTERS, type SyHand } from './synchron';

const OUT = fileURLToPath(new URL('../../../../docs/finder/synchron-hands.md', import.meta.url));
const SOLVE = { timeMs: 6000, width: 60, growth: 4, top: 3 };

/** Common openers: two starters and three cards that do nothing on your turn. */
const OPENERS: [string, string[]][] = [
  ['Junk Synchron + Jet Synchron', ['JUNK', 'JET', 'ASH', 'FUWA', 'SEMER']],
  ['Junk Synchron + Assault Synchron', ['JUNK', 'ASYN', 'ASH', 'DROLL', 'FYD']],
  ['Jet Synchron + Junk Meister', ['JET', 'MEIST', 'ASH', 'DROLL', 'FYD']],
  ['Assault Synchron + Assault Sonic Warrior', ['ASYN', 'ASW', 'ASH', 'SEMER', 'FYD']],
  ['Synchro Fellowship alone', ['FELLOW', 'ASH', 'ASH', 'DROLL', 'FYD']],
  ['Junk Synchron alone', ['JUNK', 'ASH', 'FUWA', 'MAXX', 'SEMER']],
];

/** The Synchron rules the deck file models one way, simplifies or leaves out, in plain words. */
const UNMODELLED = [
  'Psi-Reflector\'s second effect, Nightwinged Cleric\'s Set, Duel Evolution - Assault Zone\'s 2000 LP effect and Assault Sentinel\'s Type/Attribute change are not played: the list runs no "Assault Mode Activate", and the Type/Attribute change is left out (it could make a non-Dragon count for Bystial Dis Pater, or a non-DARK Tuner for Void Ogre Dragon).',
  'The Fabled Kudabbi (no "Fabled" Tuner in the list) and Majestic Star Dragon (no "Majestic Dragon") are never summoned.',
  'Synchro Emergency\'s GY effect is not played on your turn (a Synchro Summon you can make anyway); on their turn it is worth nothing.',
  'Fydraulis Harmonia is worth 0.5 in hand as a their-turn disruption; its own effect is not played out.',
  'Emergency Teleport\'s monster is not banished in the End Phase (the step says so); a Psi-Reflector left on the board is worth almost nothing anyway.',
  'Accel Synchro Stardust Dragon\'s "then Synchro Summon immediately" is a normal Synchro Summon move after it; triggers that the Tribute sets off (Assault Synchron, Stardust Trail) may resolve first, and the "unaffected" protection is not tracked.',
  'Assault Synchron\'s restriction (Synchro Monsters only from the Extra Deck while it is face-up) lasts the whole turn. Every Extra Deck monster in the list is a Synchro, so this never changes a line.',
  'Scrap Warrior\'s "add or send to the GY" is offered as two effects sharing one use. Scrap Synchron\'s and Starjunk Synchron\'s destruction-protection effects, Assault Sonic Warrior\'s and Full-Speed Warrior\'s ATK gains and Black Rose Dragon\'s ATK effect are battle or their-turn value, not played.',
  'Their-turn effects are fixed values, not played out: Baronne de Fleur (1.0), Crimson Dragon Quetzalcoatl with another Dragon Synchro to return (1.0), Bystial Dis Pater (0.9 with a banished card), Void Ogre Dragon (0.8 with an empty hand), Stardust Dragon (0.7), Accel Synchro Stardust Dragon (0.6 while Stardust Dragon is in the Extra Deck), Crimson Dragon (0.4), Junk Signal Set (0.4 with a Synchro on the field), Malong (0.3), Junk Armor protecting a Warrior or Stardust Synchro (0.3).',
  'The server\'s line checker adds up printed Levels and does not know Synchro Fellowship\'s additional Normal Summon, so a saved line that uses Junk Meister, Synchro Fellowship or Malong\'s Level changes, a Stardust Token as material, or the additional Normal Summon may show a checker error that is not a real mistake.',
];

describe('Synchron hands report', () => {
  it('writes the report', () => {
    const { engine } = loadSynchron();
    const props = engine.deck.props, ix = engine.deck.ix;
    const short = (id: string) => props[ix[id]]?.short ?? id;
    const out: string[] = [
      '# Synchron: hands to judge',
      '',
      'Generated by `client/src/finder/__harness__/synchron.hands.report.test.ts` (`npm run finder:hands` in `client/`). Do not edit by hand.',
      '',
      `${SY_STARTERS.length} going-first hands of 5, one built around each starter of the list (the other four cards seeded), then ${OPENERS.length} common openers, each solved for 6 seconds at the real search settings. For each: the hand, the steps the Finder found, the end board, what it does on their turn and in the End Phase with the values it gave them, and the score. Please play them in Master Duel and say where a line is wrong or a value is off.`,
      '',
      '## What the Finder does not know yet', '',
      'These rules are modelled one way, simplified or left out. A line that depends on one of them may be wrong or missing:', '',
      ...UNMODELLED.map((x) => '- ' + x), '',
    ];
    const hands: [string, SyHand][] = [
      ...SY_STARTERS.map((starter, i): [string, SyHand] => [short(starter), starterHand(starter, 9000 + i)]),
      ...OPENERS.map(([title, cards], i): [string, SyHand] => [title, fixedHand(cards, `opener-${i + 1}`)]),
    ];
    hands.forEach(([title, h], i) => {
      const r = engine.solveBeam(engine.newState(h.cfg), SOLVE);
      expect(r.errors).toBe(0);
      const line = r.lines[0];
      const l = engine.serializeLine(line, h.hand, 'best');
      out.push(`## ${i + 1}. ${title}: ${h.hand.map(short).join(', ')}`, '');
      if (!l.steps.length) out.push('No line: nothing worth doing with this hand.', '');
      l.steps.forEach((s, k) => out.push(`${k + 1}. ${s.text}`));
      if (l.steps.length) out.push('');
      if (l.sets.length) out.push(`Then Set ${l.sets.map(short).join(', ')}.`, '');
      const board = l.board.mons.map((m) => short(m.id)).concat(l.board.st.map((x) => short(x.id) + (x.up ? '' : ' (Set)')));
      out.push(`End board: ${board.length ? board.join(', ') : 'nothing'}.`, '');
      const { turn, end } = splitItems(l.items);
      const list = (xs: [string, number][]) => xs.map(([t, v]) => `- ${t} (${v.toFixed(2)})`);
      out.push('On their turn:', ...(turn.length ? list(turn) : ['- nothing']), '');
      if (end.length) out.push('In the End Phase:', ...list(end), '');
      out.push(`Score ${line.score.toFixed(2)} (${r.nodes} positions searched in ${(r.ms / 1000).toFixed(1)} s).`, '');
    });
    writeFileSync(OUT, out.join('\n'));
  });
});
